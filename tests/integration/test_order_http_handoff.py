def record_case(name, journal, observed, report, *, expected):
    """Opt-in private artifacts; expected violations are labelled, not hidden."""
    directory = os.environ.get("SOVA_TEST_QUALIFICATION_ARTIFACTS")
    if directory:
        path = Path(directory) / (name + ".json")
        with path.open("x") as f:
            json.dump({"case": name, "expected_resolution": expected,
                       "environment": "run-owned local PostgreSQL and loopback HTTP",
                       "client_journal": journal.snapshot(), "independent_observation": observed,
                       "measurement": report, "operational_qualification": False}, f, indent=2, sort_keys=True)
            f.write("\n")


@pytest.fixture
def http_business(business):
    # The pre-existing fixture deliberately advances its sequence only ten
    # times for fifty historical orders. A live order endpoint must start above
    # max(id); this is setup, not a relaxation of the migration's sequence test.
    with business["connect"](business["names"]["src"]) as conn:
        conn.execute("SELECT setval('order_number_seq', (SELECT max(id)+1 FROM orders), false)")
    yield business
    # Only databases/roles generated by this test's existing UUID fixture.
    with psycopg.connect(business["dsn"], autocommit=True) as admin:
        for name in business["names"].values():
            admin.execute(sql.SQL("DROP DATABASE {} WITH (FORCE)").format(sql.Identifier(name)))
        for role in (business["app"], business["batch"]):
            admin.execute(sql.SQL("DROP ROLE {}").format(sql.Identifier(role)))


def prepare(postgres_database, business, tmp_path):
    h = admitted_handoff(postgres_database, datetime.now(UTC) - timedelta(seconds=1),
                         adjust=local_budgets)
    profile = Path(__file__).resolve().parents[2] / "examples/qualification/orders-http-postgres-v1.json"
    digest = hashlib.sha256(profile.read_bytes()).hexdigest()
    journal = RequestJournal.create(tmp_path / "client.sqlite", run_id="http-" + uuid4().hex,
                                    tenant_id=h["tenant"], profile_digest=digest)
    route = Route(business["names"]["src"])
    return h, journal, route


def migrate(postgres_database, h, business, route, *, before=None):
    adapter, probes = pieces(business, h["world"]["manifest"].adapter_id,
                             source="src", target="tgt", route=route)
    result, observed = drive(h, h["revision"], h["plan"], adapter=adapter, probes=probes,
                             other_db=business["names"]["other"], scratch_db=business["names"]["scratch"],
                             operation="http-order-handoff", approval_id="approval-1", before=before)
    assert result.state == HandoffState.HANDOFF_COMPLETE, observed
    assert route.get() == business["names"]["tgt"]


def test_orders_before_during_and_after_a_real_handoff_are_reconciled(
        postgres_database, http_business, tmp_path):
    b = http_business
    h, journal, route = prepare(postgres_database, b, tmp_path)
    token = uuid4().hex
    first = OrderIntent("before", "http-customer", "before", "10")
    during = OrderIntent("during", "http-customer", "during", "20")
    last = OrderIntent("after", "http-customer", "after", "30")
    try:
        with serve(application(b, route, journal.scope, token)) as origin:
            client = OrderHttpClient(origin, bearer_token=token, journal=journal)
            try:
                assert client.submit(first) == 200
                seen = []
                def while_fenced(kind):
                    if kind == "copy_content":
                        # PostgreSQL has actually fenced the source. The real
                        # HTTP request returns 503; the retry keeps the same ID.
                        seen.append(client.submit(during))
                migrate(postgres_database, h, b, route, before=while_fenced)
                assert seen == [503]
                assert client.submit(during) == 200
                assert client.submit(last) == 200
            finally:
                client.close()
        observed = observe(b, route.get(), journal)
        report = reconcile(journal.snapshot(), observed)
        assert report["data_integrity"] == "SATISFIED"
        assert report["counts"]["confirmed_requests"] == 3
        assert report["counts"]["submission_attempts"] == 4
        assert report["counts"]["http_error_attempts"] == 1  # never erased by retry
        assert report["service_continuity"] == "NOT_QUALIFIED"
        record_case("handoff-and-retry", journal, observed, report, expected="CONFIRMED")

        # Formatting to two decimal places must not hide fractional-cent corruption.
        with b["connect"](route.get()) as conn:
            conn.execute("UPDATE orders SET amount=amount+0.001 "
                         "WHERE customer='http-customer' AND idempotency_key='before'")
        observed = observe(b, route.get(), journal)
        assert any(r["amount"] == "10.001" for r in observed["orders"])
        report = reconcile(journal.snapshot(), observed)
        assert report["data_integrity"] == "VIOLATION"
        assert any("BUSINESS_RESULT_MISMATCH" in r["violations"] for r in report["requests"])
        record_case("fractional-cent-corruption", journal, observed, report, expected="VIOLATION")

        # A negative control in the real target database, not a forged report.
        with b["connect"](route.get()) as conn:
            conn.execute("DELETE FROM idempotency_results WHERE customer='http-customer' AND idempotency_key='before'")
            conn.execute("DELETE FROM work_items WHERE order_id IN (SELECT id FROM orders WHERE customer='http-customer' AND idempotency_key='before')")
            conn.execute("DELETE FROM orders WHERE customer='http-customer' AND idempotency_key='before'")
        observed = observe(b, route.get(), journal)
        report = reconcile(journal.snapshot(), observed)
        assert report["data_integrity"] == "VIOLATION"
        assert any("ACKNOWLEDGED_RESULT_MISSING" in r["violations"] for r in report["requests"])
        record_case("missing-committed-order", journal, observed, report, expected="VIOLATION")
    finally:
        journal.close()


def test_real_commit_response_timeout_then_migration_lookup_and_retry_are_one_order(
        postgres_database, http_business, tmp_path):
    b = http_business
    h, journal, route = prepare(postgres_database, b, tmp_path)
    committed, release, finished = threading.Event(), threading.Event(), threading.Event()
    first_call = [True]
    def delay_after_commit(intent):
        if first_call[0]:
            first_call[0] = False
            committed.set()
            release.wait(timeout=2)
            finished.set()
    intent = OrderIntent("lost-response", "http-customer", "lost-response", "42")
    token = uuid4().hex
    try:
        with serve(application(b, route, journal.scope, token, after_commit=delay_after_commit)) as origin:
            client = OrderHttpClient(origin, bearer_token=token, journal=journal, timeout=0.1)
            try:
                assert client.submit(intent) is None
                assert committed.wait(timeout=2)
                release.set()
                assert finished.wait(timeout=2)
                initial_observed = observe(b, route.get(), journal)
                before = reconcile(journal.snapshot(), initial_observed)
                assert before["requests"][0]["resolution"] == "UNRESOLVED_COMMIT"
                record_case("commit-response-lost", journal, initial_observed, before, expected="UNRESOLVED_COMMIT")
                migrate(postgres_database, h, b, route)
                assert client.lookup(intent) == 200
                assert client.submit(intent) == 200  # same logical request, not another order
            finally:
                release.set()
                client.close()
        observed = observe(b, route.get(), journal)
        assert len(observed["orders"]) == 1
        report = reconcile(journal.snapshot(), observed)
        assert report["requests"][0]["resolution"] == "CONFIRMED"
        assert report["counts"]["transport_error_attempts"] == 1
        assert report["counts"]["submission_attempts"] == 2
        assert report["data_integrity"] == "SATISFIED"
        record_case("lookup-and-idempotent-retry", journal, observed, report, expected="CONFIRMED")
    finally:
        release.set()
        journal.close()


def test_bad_http_identity_and_wrong_tenant_never_create_an_order(
        postgres_database, http_business, tmp_path):
    b = http_business
    h, journal, route = prepare(postgres_database, b, tmp_path)
    token = uuid4().hex
    intent = OrderIntent("denied", "http-customer", "denied", "1")
    try:
        with serve(application(b, route, journal.scope, token)) as origin:
            client = OrderHttpClient(origin, bearer_token="wrong", journal=journal)
            try:
                assert client.submit(intent) == 401
            finally:
                client.close()
            other = RequestJournal.create(tmp_path / "other.sqlite", run_id=journal.scope["run_id"],
                                           tenant_id="another-tenant", profile_digest="a" * 64)
            client = OrderHttpClient(origin, bearer_token=token, journal=other)
            try:
                assert client.submit(intent) == 403
            finally:
                client.close()
                other.close()
        observed = observe(b, route.get(), journal)
        assert observed["orders"] == []
        report = reconcile(journal.snapshot(), observed)
        assert report["requests"][0]["resolution"] == "NOT_COMMITTED"
        record_case("unauthorized-no-order", journal, observed, report, expected="NOT_COMMITTED")
    finally:
        journal.close()
